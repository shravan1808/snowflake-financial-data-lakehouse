CREATE OR REPLACE TABLE FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_TRANSACTION_SUMMARY
(
TRANSACTION_TYPE STRING,
TRANSACTION_VOLUME NUMBER,
TRANSACTION_AMOUNT NUMBER(25,2),
FRAUD_TOTAL NUMBER
)
AS
SELECT  TYPE AS TRANSACTION_TYPE,
        COUNT(*) AS TRANSACTION_VOLUME,
        SUM(AMOUNT) AS TRANSACTION_AMOUNT,
        COUNT_IF(ISFRAUD = 1) AS FRAUD_TOTAL
FROM FINANCIAL_LAKEHOUSE_DB.SILVER_CURATED.TRANSACTIONS_CLEAN
GROUP BY TYPE;

SELECT *
FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_TRANSACTION_SUMMARY
ORDER BY TRANSACTION_AMOUNT DESC;

CREATE OR REPLACE TABLE FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_FRAUD_ANALYTICS
(
TRANSACTION_TYPE STRING,
TOTAL_TRANSACTIONS NUMBER,
FRAUD_TRANSACTION_COUNT NUMBER,
FRAUD_RATE NUMBER(10,4),
FRAUD_AMOUNT NUMBER(20,2)
)
AS
SELECT  TYPE AS TRANSACTION_TYPE,
        COUNT(*) AS TOTAL_TRANSACTIONS,
        COUNT_IF(ISFRAUD=1) AS FRAUD_TRANSACTION_COUNT,
        (COUNT_IF(ISFRAUD=1)/COUNT(*))*100 AS FRAUD_RATE,
        SUM(IFF(ISFRAUD=1,AMOUNT,0)) AS FRAUD_AMOUNT
FROM FINANCIAL_LAKEHOUSE_DB.SILVER_CURATED.TRANSACTIONS_CLEAN
GROUP BY TYPE;

SELECT *
FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_FRAUD_ANALYTICS
ORDER BY FRAUD_AMOUNT DESC;

CREATE OR REPLACE TABLE FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_STEP_ANALYTICS
(
STEP NUMBER,
TOTAL_TRANSACTIONS NUMBER,
TOTAL_AMOUNT NUMBER(25,2),
FRAUD_COUNT NUMBER,
FRAUD_AMOUNT NUMBER(25,2),
FRAUD_RATE NUMBER(10,4)
)
AS
SELECT  STEP,
        COUNT(*) AS TOTAL_TRANSACTIONS,
        SUM(AMOUNT) AS TOTAL_AMOUNT,
        COUNT_IF(ISFRAUD=1) AS FRAUD_COUNT,
        SUM(IFF(ISFRAUD=1,AMOUNT,0)) AS FRAUD_AMOUNT,
        (COUNT_IF(ISFRAUD=1)/COUNT(*))*100 AS FRAUD_RATE
FROM FINANCIAL_LAKEHOUSE_DB.SILVER_CURATED.TRANSACTIONS_CLEAN
GROUP BY STEP;

SELECT * 
FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_STEP_ANALYTICS
ORDER BY FRAUD_RATE DESC,FRAUD_AMOUNT DESC
LIMIT 10;


SELECT STEP,COUNT(*) AS DUPLICATE_RECORDS
FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_STEP_ANALYTICS
GROUP BY STEP
HAVING COUNT(*)>1;

SELECT COUNT(*) AS TOTAL_STEPS,
        COUNT(DISTINCT STEP) AS DISTINCT_STEPS,
        MIN(STEP) AS MIN_STEP,
        MAX(STEP) AS MAX_STEP
FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_STEP_ANALYTICS;

SELECT (SELECT COUNT(*)
        FROM FINANCIAL_LAKEHOUSE_DB.SILVER_CURATED.TRANSACTIONS_CLEAN) AS TOTAL_RECORDS_SILVER,
        (SELECT SUM(TOTAL_TRANSACTIONS)
        FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_STEP_ANALYTICS) AS TOTAL_RECORDS_GOLD,
        (SELECT SUM(AMOUNT)
        FROM FINANCIAL_LAKEHOUSE_DB.SILVER_CURATED.TRANSACTIONS_CLEAN) AS TOTAL_AMOUNT_SILVER,
        (SELECT SUM(TOTAL_AMOUNT)
        FROM FINANCIAL_LAKEHOUSE_DB.GOLD_ANALYTICS.GOLD_STEP_ANALYTICS) AS TOTAL_AMOUNT_GOLD;


DESC TABLE FINANCIAL_LAKEHOUSE_DB.SILVER_CURATED.TRANSACTIONS_CLEAN;