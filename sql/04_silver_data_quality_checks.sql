SELECT COUNT(*) AS NULL_COUNT
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE
WHERE STEP IS NULL OR TYPE IS NULL OR AMOUNT IS NULL OR NAMEORIG IS NULL OR ISFRAUD IS NULL;

SELECT COUNT(*) AS ZERO_AMT_ROW_COUNT
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE
WHERE AMOUNT <=0;

SELECT COUNT(*) AS INVALID_FRAUD_COUNT
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE
WHERE ISFRAUD NOT IN (0,1) OR ISFRAUD IS NULL;

SELECT  TYPE,
        COUNT(*) AS TYPE_COUNT
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE
GROUP BY TYPE;