SELECT COUNT(*) AS ROW_COUNT 
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE;

SELECT  ISFRAUD, 
        COUNT(*) AS ROW_COUNT
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE
GROUP BY ISFRAUD;

SELECT  TYPE,
        COUNT(*) AS ROW_COUNT
FROM FINANCIAL_LAKEHOUSE_DB.BRONZE_RAW.RAW_BRONZE_TABLE
GROUP BY TYPE
ORDER BY ROW_COUNT DESC;